-- J M Enterprise Travel: public enquiry storage and package catalogue access.
-- Safe to re-run. Customer enquiries are INSERT-only for public visitors.

create table if not exists public.booking_enquiries (
  id bigint generated by default as identity primary key,
  enquiry_type text not null,
  from_location text,
  destination text,
  travel_date date,
  travellers text,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.booking_enquiries enable row level security;
alter table public.contact_enquiries enable row level security;

drop policy if exists "Public can submit booking enquiries" on public.booking_enquiries;
create policy "Public can submit booking enquiries"
  on public.booking_enquiries for insert to anon, authenticated
  with check (true);

drop policy if exists "Public can submit contact enquiries" on public.contact_enquiries;
create policy "Public can submit contact enquiries"
  on public.contact_enquiries for insert to anon, authenticated
  with check (true);

revoke all on public.booking_enquiries from anon, authenticated;
revoke all on public.contact_enquiries from anon, authenticated;
grant insert on public.booking_enquiries to anon, authenticated;
grant insert on public.contact_enquiries to anon, authenticated;
grant usage, select on sequence public.booking_enquiries_id_seq to anon, authenticated;
grant usage, select on sequence public.contact_enquiries_id_seq to anon, authenticated;

-- The website may display active packages; it cannot change catalogue records.
alter table public.travel_packages enable row level security;
drop policy if exists "Public can read active travel packages" on public.travel_packages;
create policy "Public can read active travel packages"
  on public.travel_packages for select to anon, authenticated
  using (is_active = true);
drop policy if exists "Public can view active packages" on public.travel_packages;
revoke all on public.travel_packages from anon, authenticated;
grant select on public.travel_packages to anon, authenticated;

-- Legacy table is intentionally not exposed to public API access.
revoke all on public."Travel Packages" from anon, authenticated;

-- This event-trigger helper is not a public RPC endpoint.
revoke all on function public.rls_auto_enable() from public, anon, authenticated;

-- No public SELECT policies are created for enquiry tables:
-- submitted customer details are not publicly readable.
